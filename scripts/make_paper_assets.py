from matplotlib.patches import Patch
import numpy as np

REPO = Path(__file__).resolve().parent.parent
ANALYSIS = REPO / "analysis"
TABLES = REPO / "paper" / "tables"
FIGURES = REPO / "paper" / "figures"

MAIN_TR = [
    "Qwen3.6-35B-A3B",
    "deepseek-v4-flash",
    "gemini-3.6-flash-tr",
    "gemini-2.5-flash-lite-tr",
]
CORRECT_COL = {m: f"{m} correct" for m in MAIN_TR}

DISPLAY = {
    "Qwen3.6-35B-A3B": "Qwen3.6-35B-A3B",
    "deepseek-v4-flash": "DeepSeek-V4-Flash",
    "gemini-3.6-flash-tr": "Gemini-3.6-Flash",
    "gemini-3.6-flash-en": "Gemini-3.6-Flash",
    "gemini-2.5-flash-lite-tr": "Gemini-2.5-Flash-Lite",
    "gemini-2.5-flash-lite-en": "Gemini-2.5-Flash-Lite",
}
CAT_SHORT = {
    "Cuisine": "Cuisine",
    "Literature": "Literature",
    "Sport": "Sport",
    "Politics": "Politics",
    "History": "History",
    "Music": "Music",
    "Media, TV, film, Entertainment": "Media/TV",
    "Traditions & Folk Culture": "Traditions",
    "Places & Landmarks": "Landmarks",
}

# Paul Tol muted (CVD-safe); iki Gemini ayni aile -> koyu/acik mavi
MODEL_COLOR = {
    "gemini-3.6-flash-tr": "#332288",
    "gemini-2.5-flash-lite-tr": "#88CCEE",
    "deepseek-v4-flash": "#CC6677",
    "Qwen3.6-35B-A3B": "#117733",
}
# n_correct 0..4 (indeks=n): koyu = zor; komsu adimlar net ayrisacak sekilde
DIFFICULTY_RAMP = ["#08306B", "#2A6FB0", "#5B9BD1", "#A3C9E5", "#DCE9F6"]
# prompt dili (iki panelde ayni): TR mavi, EN turuncu (Okabe-Ito, CVD-safe)
LANG_COLOR = {"TR": "#0072B2", "EN": "#E69F00"}
INK = "#000000"
MUTED = "#555555"
GRID = "#D9D9D9"


def read_tsv(path):
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def latex_escape(s: str) -> str:
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


# =============================================================================
# 1) n_correct kolonu -> analysis/model_correct.tsv
# =============================================================================
def add_n_correct():
    path = ANALYSIS / "model_correct.tsv"
    rows = read_tsv(path)
    fields = list(rows[0].keys())
    if "n_correct" in fields:
        fields.remove("n_correct")
    fields.append("n_correct")

    dist = {k: 0 for k in range(len(MAIN_TR) + 1)}
    for r in rows:
        n = sum(1 for m in MAIN_TR if (r.get(CORRECT_COL[m]) or "").strip() == "True")
        r["n_correct"] = str(n)
        dist[n] += 1

    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields, delimiter="\t")
        w.writeheader()
        w.writerows(rows)

    total = sum(dist.values())
    print(f"n_correct eklendi ({total} satir): " +
          ", ".join(f"n={k}:{v}" for k, v in sorted(dist.items())))
    return dist, total


