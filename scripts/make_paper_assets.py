def write_prompt_ablation_table(acc):
    families = [
        ("Gemini-3.6-Flash", "gemini-3.6-flash-tr", "gemini-3.6-flash-en"),
        ("Gemini-2.5-Flash-Lite", "gemini-2.5-flash-lite-tr", "gemini-2.5-flash-lite-en"),
    ]
    lines = [
        r"% Auto-generated by scripts/make_paper_assets.py — do not edit by hand.",
        r"\begin{table}[t]",
        r"  \centering",
        r"  \caption{Effect of prompt language on the two Gemini models. "
        r"$\Delta$ is EN$-$TR (percentage points). For Gemini-3.6-Flash the gap "
        r"stems entirely from the \emph{Places \& Landmarks} category.}",
        r"  \label{tab:prompt-ablation}",
        r"  \begin{tabular}{lrrr}",
        r"    \toprule",
        r"    Model & TR (\%) & EN (\%) & $\Delta$ \\",
        r"    \midrule",
    ]
    for disp, tr, en in families:
        lines.append(f"    {disp} & {acc[tr]:.1f} & {acc[en]:.1f} & "
                     f"{acc[en] - acc[tr]:+.1f} \\\\")
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]
    (TABLES / "prompt_ablation.tex").write_text("\n".join(lines), encoding="utf-8")
    print("yazildi -> paper/tables/prompt_ablation.tex")


