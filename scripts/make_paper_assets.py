def setup_style():
    plt.rcParams.update({
        "figure.dpi": 150,
        "savefig.dpi": 300,
        "savefig.bbox": "tight",
        "font.size": 9,
        "font.family": "serif",
        "font.serif": ["STIXGeneral", "STIX", "Times New Roman", "DejaVu Serif"],
        "mathtext.fontset": "stix",
        "axes.edgecolor": INK,
        "axes.linewidth": 0.6,
        "axes.labelsize": 9,
        "xtick.labelsize": 8,
        "ytick.labelsize": 8,
        "xtick.major.size": 2.5,
        "ytick.major.size": 2.5,
        "xtick.major.width": 0.6,
        "ytick.major.width": 0.6,
        "legend.fontsize": 7.5,
        "legend.frameon": False,
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.axisbelow": True,
        "grid.color": GRID,
        "grid.linewidth": 0.4,
    })


def _difficulty_legend_handles(dist):
    return [Patch(facecolor=DIFFICULTY_RAMP[k], edgecolor="#CCCCCC",
                  linewidth=0.4, label=f"{k}  (n={dist[k]})")
            for k in sorted(dist, reverse=True)]


def fig_main_results():
    """Genel accuracy (4 ana TR model): yatay bar, en iyi ustte; renkler
    category_accuracy ile ayni, deger etiketi bar ucunda."""
    macc = {r["Model"]: float(r["Accuracy(%)"])
            for r in read_tsv(ANALYSIS / "model_accuracy.tsv")}
    models = sorted(MAIN_TR, key=lambda m: -macc[m])
    ys = np.arange(len(models))[::-1]

    fig, ax = plt.subplots(figsize=(3.2, 1.55))
    ax.xaxis.grid(True)
    for y, m in zip(ys, models):
        ax.barh(y, macc[m], height=0.62, color=MODEL_COLOR[m],
                edgecolor="white", linewidth=0.4, zorder=3)
        ax.text(macc[m] + 1.5, y, f"{macc[m]:.1f}", ha="left", va="center",
                fontsize=7.5, color=INK)
    ax.set_yticks(ys)
    ax.set_yticklabels([DISPLAY[m] for m in models])
    ax.set_xlim(0, 100)
    ax.set_xticks([0, 25, 50, 75, 100])
    ax.set_ylim(-0.55, len(models) - 0.45)
    ax.set_xlabel("Accuracy (%)")
    ax.tick_params(axis="y", length=0)

    fig.savefig(FIGURES / "main_results.png")
    plt.close(fig)
    print("yazildi -> paper/figures/main_results.png")


def fig_category_overall():
    """Model-siz kategori accuracy: kategori basina TUM generation'lar
    havuzlanir (dogru generation / (4 model x n_soru)); yatay bar,
    kolay->zor sirali."""
    cats, counts, mat = (None, None, None)
    mat = {r["Model"]: r for r in read_tsv(ANALYSIS / "model_x_category_accuracy.tsv")}
    counts = {r["Category"]: r["Questions"]
              for r in read_tsv(ANALYSIS / "category_accuracy.tsv")}
    # ayni n uzerinden esit agirlik -> havuzlanmis accuracy = 4-model ortalamasi
    pooled = {c: np.mean([float(mat[m][c]) for m in MAIN_TR]) for c in counts}
    cats = sorted(counts, key=lambda c: -pooled[c])
    ys = np.arange(len(cats))[::-1]

    # renk = zorluk (koyu = zor); difficulty figuruyle ayni gorsel dil
    lo, hi = min(pooled.values()), max(pooled.values())
    def shade(v):  # v yuksek (kolay) -> acik; dusuk (zor) -> koyu
        t = (v - lo) / (hi - lo) if hi > lo else 0.5
        c0, c1 = (8, 48, 107), (163, 201, 229)  # #08306B -> #A3C9E5
        return "#%02X%02X%02X" % tuple(round(a + t * (b - a)) for a, b in zip(c0, c1))

    fig, ax = plt.subplots(figsize=(3.2, 2.4))
    ax.xaxis.grid(True)
    for y, c in zip(ys, cats):
        ax.barh(y, pooled[c], height=0.85, color=shade(pooled[c]),
                edgecolor="white", linewidth=0.6, zorder=3)
        ax.text(pooled[c] + 1.5, y, f"{pooled[c]:.1f}", ha="left",
                va="center", fontsize=7.5, color=INK)
    ax.set_yticks(ys)
    ax.set_yticklabels([f"{CAT_SHORT[c]} (n={counts[c]})" for c in cats])
    ax.set_xlim(0, 100)
    ax.set_xticks([0, 25, 50, 75, 100])
    ax.set_ylim(-0.55, len(cats) - 0.45)
    ax.set_xlabel("Accuracy over all generations (%)")
    ax.tick_params(axis="y", length=0)

    fig.savefig(FIGURES / "category_overall.png")
    plt.close(fig)
    print("yazildi -> paper/figures/category_overall.png")


def fig_difficulty_stackbar(dist, total):
    """Soru-zorluk dagilimi: tek yatay %100 stacked bar."""
    fig, ax = plt.subplots(figsize=(3.6, 0.8))
    left = 0.0
    for k in sorted(dist, reverse=True):  # 4 -> 0
        v = dist[k]
        ax.barh(0, v, left=left, height=0.5, color=DIFFICULTY_RAMP[k],
                edgecolor="white", linewidth=1.0, zorder=3)
        cx = left + v / 2
        if v >= 6:
            ax.text(cx, 0, str(v), ha="center", va="center", fontsize=7.5,
                    color="white" if k <= 1 else "#1A1A1A")
        else:  # cok dar segment: adet yukarida, kisa baglantiyla
            ax.plot([cx, cx], [0.27, 0.40], color="#999999", linewidth=0.5)
            ax.text(cx, 0.43, str(v), ha="center", va="bottom",
                    fontsize=7, color=MUTED)
        left += v

    ax.set_xlim(0, total)
    ax.set_ylim(-0.35, 0.62)
    ax.set_yticks([])
    ax.set_xticks([])
    ax.spines["left"].set_visible(False)
    ax.spines["bottom"].set_visible(False)
    ax.legend(handles=_difficulty_legend_handles(dist),
              title="Models correct", title_fontsize=7.5, ncol=5,
              loc="upper center", bbox_to_anchor=(0.5, -0.02),
              handlelength=1.0, handleheight=1.0, columnspacing=0.9,
              handletextpad=0.4)

    fig.savefig(FIGURES / "difficulty_stackbar.png")
    plt.close(fig)
    print("yazildi -> paper/figures/difficulty_stackbar.png")


def fig_prompt_effect(acc):
    """Iki yan yana panel, her panel KENDI (zoom) y-olcegi; bar rengi =
    PROMPT DILI (iki panelde ayni), barlar bitisik; eksen-kirigi isaretli."""
    panels = [
        ("Gemini-3.6-Flash", "gemini-3.6-flash", (92, 98), [92, 94, 96, 98]),
        ("Gemini-2.5-Flash-Lite", "gemini-2.5-flash-lite", (55, 70), [55, 60, 65, 70]),
    ]
    W = 0.5  # bar genisligi; x=0 ve x=W -> bitisik

    fig, axes = plt.subplots(1, 2, figsize=(3.3, 2.0))
    fig.subplots_adjust(wspace=0.55)
    for ax, (disp, key, ylim, yticks) in zip(axes, panels):
        tr_a, en_a = acc[f"{key}-tr"], acc[f"{key}-en"]
        ax.yaxis.grid(True)
        ax.bar(0, tr_a, width=W, facecolor=LANG_COLOR["TR"],
               edgecolor="white", linewidth=0.6, zorder=3)
        ax.bar(W, en_a, width=W, facecolor=LANG_COLOR["EN"],
               edgecolor="white", linewidth=0.6, zorder=3)
        for x, v in ((0, tr_a), (W, en_a)):
            ax.text(x, v + (ylim[1] - ylim[0]) * 0.015, f"{v:.1f}",
                    ha="center", va="bottom", fontsize=7.5, color=INK)
        ax.text(0.5, 1.0, f"$\\Delta$ = {en_a - tr_a:+.1f}",
                transform=ax.transAxes, ha="center", va="bottom",
                fontsize=7.5, color=MUTED)
        ax.set_title(disp, fontsize=8, pad=13)
        ax.set_xticks([])
        ax.set_xlim(-0.75, W + 0.75)
        ax.set_ylim(*ylim)
        ax.set_yticks(yticks)
        # kesik-eksen isareti (y ekseni 0'dan baslamiyor)
        d = 0.015
        ax.plot((-d * 2.2, d * 2.2), (-d, d), transform=ax.transAxes,
                color=INK, linewidth=0.7, clip_on=False)
    axes[0].set_ylabel("Accuracy (%)")

    handles = [Patch(facecolor=LANG_COLOR["TR"], label="Turkish prompt"),
               Patch(facecolor=LANG_COLOR["EN"], label="English prompt")]
    fig.legend(handles=handles, ncol=2, loc="lower center",
               bbox_to_anchor=(0.5, 1.03), handlelength=1.0,
               handleheight=1.0, handletextpad=0.5, columnspacing=1.2)

    fig.savefig(FIGURES / "prompt_effect.png")
    plt.close(fig)
    print("yazildi -> paper/figures/prompt_effect.png")


def fig_category_accuracy():
    """Grouped bar: kategoriler altta (kolay->zor), her kategoride 4 bar,
    renk = model, legend ustte."""
    mat = {r["Model"]: r for r in read_tsv(ANALYSIS / "model_x_category_accuracy.tsv")}
    counts = {r["Category"]: r["Questions"]
              for r in read_tsv(ANALYSIS / "category_accuracy.tsv")}
    cats = sorted(counts, key=lambda c: -np.mean([float(mat[m][c]) for m in MAIN_TR]))
    macc = {r["Model"]: float(r["Accuracy(%)"])
            for r in read_tsv(ANALYSIS / "model_accuracy.tsv")}
    models = sorted(MAIN_TR, key=lambda m: -macc[m])

    x = np.arange(len(cats))
    n = len(models)
    w = 0.19

    fig, ax = plt.subplots(figsize=(6.3, 2.2))
    ax.yaxis.grid(True)
    for i, m in enumerate(models):
        vals = [float(mat[m][c]) for c in cats]
        ax.bar(x + (i - (n - 1) / 2) * w, vals, w, label=DISPLAY[m],
               color=MODEL_COLOR[m], edgecolor="white", linewidth=0.4, zorder=3)

    ax.set_xticks(x)
    ax.set_xticklabels([f"{CAT_SHORT[c]}\n(n={counts[c]})" for c in cats])
    ax.set_ylabel("Accuracy (%)")
    ax.set_ylim(0, 100)
    ax.set_yticks([0, 25, 50, 75, 100])
    ax.set_xlim(-0.55, len(cats) - 0.45)
    ax.tick_params(axis="x", length=0)
    ax.legend(ncol=4, loc="lower center", bbox_to_anchor=(0.5, 1.02),
              handlelength=1.0, handleheight=1.0, handletextpad=0.5,
              columnspacing=1.3)

    fig.savefig(FIGURES / "category_accuracy.png")
    plt.close(fig)
    print("yazildi -> paper/figures/category_accuracy.png")


# =============================================================================
def main():
    TABLES.mkdir(parents=True, exist_ok=True)
    FIGURES.mkdir(parents=True, exist_ok=True)

    acc = {r["Model"]: float(r["Accuracy(%)"])
           for r in read_tsv(ANALYSIS / "model_accuracy.tsv")}

    dist, total = add_n_correct()
    write_prompt_ablation_table(acc)

    setup_style()
    fig_main_results()
    fig_category_overall()
    fig_difficulty_stackbar(dist, total)
    fig_prompt_effect(acc)
    fig_category_accuracy()

    print("\nTamamlandi. paper/tables/*.tex + paper/figures/*.png")


if __name__ == "__main__":
    main()
